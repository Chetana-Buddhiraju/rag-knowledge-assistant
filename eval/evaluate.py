"""Evaluation harness: runs eval/dataset.json through a given (backend, profile),
computes retrieval / generation / system metrics, and writes eval/results/<profile>.json.

Run baseline then improved (same backend) and diff the two to produce the
Step 4 deliverable ("baseline vs improved, explain which changes improved
which metrics") — see eval/results/comparison.md, generated by
eval/compare.py after both runs exist.

Usage:
    python eval/evaluate.py --profile baseline
    python eval/evaluate.py --profile improved
    BACKEND=azure python eval/evaluate.py --profile improved
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.access_control import get_allowed_departments  # noqa: E402
from src.config import PROFILES, Settings  # noqa: E402
from src.rag_pipeline import RAGPipeline  # noqa: E402

DATASET_PATH = Path(__file__).resolve().parent / "dataset.json"
RESULTS_DIR = Path(__file__).resolve().parent / "results"

# Illustrative Azure OpenAI list pricing (USD / 1M tokens) for approximate cost
# reporting only — check the Azure OpenAI pricing page for current rates.
PRICING_PER_1M = {"prompt": 0.15, "completion": 0.60}


def _keyword_coverage(answer_text: str, keywords: list[str]) -> float:
    if not keywords:
        return 1.0
    text = answer_text.lower()
    hits = sum(1 for kw in keywords if kw.lower() in text)
    return hits / len(keywords)


def _doc_ids_in_hits(hits) -> list[str]:
    return [h.record["doc_id"] for h in hits]


def _departments_in_hits(hits) -> set[str]:
    return {h.record["department"] for h in hits}


def _eval_turn(pipeline: RAGPipeline, turn: dict, role: str, history: list[dict]) -> dict:
    allowed = get_allowed_departments(role)
    t0 = time.perf_counter()
    result = pipeline.ask(turn["query"], allowed, history)
    wall_ms = (time.perf_counter() - t0) * 1000

    expected_docs = turn.get("expected_doc_ids", [])
    forbidden_depts = set(turn.get("forbidden_departments", []))

    retrieved_docs = _doc_ids_in_hits(result.hits)
    retrieved_depts = _departments_in_hits(result.hits)

    hit_rate = None
    precision_at_k = None
    if expected_docs:
        hit_rate = 1.0 if any(d in expected_docs for d in retrieved_docs) else 0.0
        precision_at_k = (
            sum(1 for d in retrieved_docs if d in expected_docs) / len(retrieved_docs)
            if retrieved_docs else 0.0
        )

    acl_violation = bool(retrieved_depts & forbidden_depts)

    ambiguous_correct = None
    if turn.get("expect_ambiguous"):
        ambiguous_correct = result.ambiguous == True  # noqa: E712

    insufficient_correct = None
    keyword_coverage = None
    groundedness = None
    citation_correct = None
    hallucinated = False
    used_llm = False
    token_total = 0

    if not result.ambiguous:
        answer = result.answer
        insufficient_correct = answer.insufficient_evidence == turn.get("expect_insufficient_evidence", False)

        if turn.get("expect_insufficient_evidence"):
            # Hallucination = the system answered confidently when it should have said "insufficient evidence".
            hallucinated = not answer.insufficient_evidence
        elif not answer.insufficient_evidence:
            keyword_coverage = _keyword_coverage(answer.text, turn.get("expected_answer_keywords", []))
            if answer.guardrail:
                groundedness = answer.guardrail.groundedness_ratio
                hallucinated = answer.guardrail.flagged
            if expected_docs and answer.citations:
                cited_doc_ids = {
                    result.hits[c.index - 1].record["doc_id"]
                    for c in answer.citations
                    if 0 < c.index <= len(result.hits)
                }
                citation_correct = bool(cited_doc_ids & set(expected_docs))
            used_llm = answer.used_llm
            token_total = answer.token_usage.total

    return {
        "query": turn["query"],
        "rewritten_query": result.rewritten_query,
        "ambiguous_predicted": result.ambiguous,
        "hit_rate": hit_rate,
        "precision_at_k": precision_at_k,
        "acl_violation": acl_violation,
        "ambiguous_correct": ambiguous_correct,
        "insufficient_correct": insufficient_correct,
        "keyword_coverage": keyword_coverage,
        "groundedness": groundedness,
        "citation_correct": citation_correct,
        "hallucinated": hallucinated,
        "latency_ms": wall_ms,
        "token_total": token_total,
        "used_llm": used_llm,
        "answer_preview": (result.answer.text[:200] if result.answer else "(clarification requested)"),
    }, result


def run_eval(profile_name: str, backend: str | None) -> dict:
    settings = Settings()
    settings.profile_name = profile_name
    if backend:
        settings.backend = backend
    pipeline = RAGPipeline(settings)

    with open(DATASET_PATH, "r", encoding="utf-8") as f:
        cases = json.load(f)

    per_case_results = []
    for case in cases:
        role = case.get("role", "admin")
        if case["type"] == "single":
            turn_result, _ = _eval_turn(pipeline, case, role, [])
            per_case_results.append({"id": case["id"], "category": case["category"], "turns": [turn_result]})
        else:
            history: list[dict] = []
            turn_results = []
            for turn in case["turns"]:
                turn_result, result = _eval_turn(pipeline, turn, role, history)
                turn_results.append(turn_result)
                history.append({"role": "user", "content": turn["query"]})
                answer_text = result.answer.text if result.answer else "(asked for clarification)"
                history.append({"role": "assistant", "content": answer_text})
            per_case_results.append({"id": case["id"], "category": case["category"], "turns": turn_results})

    summary = _summarize(per_case_results)
    return {
        "profile": profile_name,
        "backend": settings.backend,
        "cases": per_case_results,
        "summary": summary,
    }


def _avg(values: list[float]) -> float | None:
    values = [v for v in values if v is not None]
    return round(statistics.mean(values), 4) if values else None


def _summarize(per_case_results: list[dict]) -> dict:
    all_turns = [t for c in per_case_results for t in c["turns"]]

    total_tokens = sum(t["token_total"] for t in all_turns)
    any_llm_used = any(t["used_llm"] for t in all_turns)
    est_cost_usd = None
    if any_llm_used:
        # Approximation: without separate prompt/completion token breakdown per
        # turn here, split 85/15 (typical for RAG: large context, short answer).
        est_cost_usd = round(
            total_tokens * 0.85 / 1_000_000 * PRICING_PER_1M["prompt"]
            + total_tokens * 0.15 / 1_000_000 * PRICING_PER_1M["completion"],
            5,
        )

    return {
        "n_cases": len(per_case_results),
        "n_turns": len(all_turns),
        "retrieval": {
            "hit_rate": _avg([t["hit_rate"] for t in all_turns]),
            "precision_at_k": _avg([t["precision_at_k"] for t in all_turns]),
        },
        "generation": {
            "answer_keyword_coverage": _avg([t["keyword_coverage"] for t in all_turns]),
            "groundedness": _avg([t["groundedness"] for t in all_turns]),
            "citation_correctness": _avg([1.0 if t["citation_correct"] else 0.0 for t in all_turns if t["citation_correct"] is not None]),
            "hallucination_rate": _avg([1.0 if t["hallucinated"] else 0.0 for t in all_turns]),
            "ambiguous_detection_accuracy": _avg([1.0 if t["ambiguous_correct"] else 0.0 for t in all_turns if t["ambiguous_correct"] is not None]),
            "insufficient_evidence_accuracy": _avg([1.0 if t["insufficient_correct"] else 0.0 for t in all_turns if t["insufficient_correct"] is not None]),
        },
        "access_control": {
            "acl_violation_rate": _avg([1.0 if t["acl_violation"] else 0.0 for t in all_turns]),
        },
        "system": {
            "avg_latency_ms": _avg([t["latency_ms"] for t in all_turns]),
            "p95_latency_ms": round(sorted(t["latency_ms"] for t in all_turns)[int(0.95 * (len(all_turns) - 1))], 2) if all_turns else None,
            "total_tokens": total_tokens,
            "estimated_cost_usd": est_cost_usd,
            "llm_used": any_llm_used,
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", choices=list(PROFILES.keys()), required=True)
    parser.add_argument("--backend", choices=["local", "github", "azure"], default=None)
    args = parser.parse_args()

    result = run_eval(args.profile, args.backend)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = RESULTS_DIR / f"{args.profile}.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)

    print(json.dumps(result["summary"], indent=2))
    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    main()
